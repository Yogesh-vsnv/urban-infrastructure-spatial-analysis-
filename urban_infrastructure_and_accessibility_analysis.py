#Raster analysis(rasterio + numpy)

import numpy as np
import rasterio

from rasterio.transform import from_bounds
from rasterio.features import rasterize

# Define raster resolution
pixel_size = 10

# Get study area boundaries
minx, miny, maxx, maxy = study_area.bounds

# Calculate raster dimensions
width = int((maxx - minx) / pixel_size)
height = int((maxy - miny) / pixel_size)

# Create raster transformation
transform = from_bounds(
    minx, miny, maxx, maxy,
    width, height
)

print("Raster width:", width)
print("Raster height:", height)
print("Pixel size:", pixel_size, "metres")
print("Total pixels:", width * height)

#convert building polygons into raster

# Convert building geometries into raster shapes
building_shapes = (
    (geometry, 1)
    for geometry in buildings_analysis.geometry
)

# Rasterize building polygons
building_raster = rasterize(
    shapes=building_shapes,
    out_shape=(height, width),
    transform=transform,
    fill=0,
    dtype="uint8"
)

print("Rasterization completed!")
print("Raster shape:", building_raster.shape)
print("Data type:", building_raster.dtype)
print("Unique values:", np.unique(building_raster))

#Calculate building-covered area using NumPy

# Count building pixels
building_pixels = np.count_nonzero(building_raster == 1)

# Count empty pixels
empty_pixels = np.count_nonzero(building_raster == 0)

# Calculate area of one pixel
pixel_area = pixel_size * pixel_size

# Calculate total building-covered area
building_area = building_pixels * pixel_area

# Convert to hectares
building_area_hectares = building_area / 10000

# Calculate percentage coverage
building_percentage = (
    building_pixels / building_raster.size
) * 100

print("Building pixels:", building_pixels)
print("Empty pixels:", empty_pixels)
print("Total pixels:", building_raster.size)

print("Building area (sq. m):", building_area)
print("Building area (hectares):", round(building_area_hectares, 2))
print("Building coverage:", round(building_percentage, 2), "%")

#visualise building raster

import matplotlib.pyplot as plt

plt.figure(figsize=(10, 8))

